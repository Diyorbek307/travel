import type { NextConfig } from "next";

/**
 * Отпечаток сборки для Service Worker.
 *
 * Без него офлайн-кэш никогда не обновлялся: в sw.js версия была зашита
 * строкой "v1", а очистка при активации удаляет кэши, «не заканчивающиеся
 * на текущую версию» — то есть shell-v1 под условие не попадал и жил
 * вечно. Приложение выкатывалось, а турист продолжал видеть старую
 * оболочку, пока вручную не сбросит данные сайта.
 *
 * На Render берём хэш коммита, локально — время сборки: важно лишь то,
 * что значение меняется от сборки к сборке.
 */
const BUILD_ID =
  process.env.RENDER_GIT_COMMIT?.slice(0, 12) ?? String(Date.now());

const nextConfig: NextConfig = {
  serverExternalPackages: ["node:sqlite"],
  eslint: { ignoreDuringBuilds: true },
  env: { NEXT_PUBLIC_BUILD_ID: BUILD_ID },

  images: {
    /*
     * Главный экран показывает до сорока снимков, и каждый Next
     * пережимает на своей стороне при первом запросе. По умолчанию
     * результат живёт в кэше всего минуту — то есть на хостинге со
     * слабым процессором те же сорок картинок пережимались снова
     * каждую минуту, и вкладка крутилась, пока это шло. Снимки у нас
     * неизменные: имя файла меняется вместе с содержимым, поэтому
     * держать год безопасно.
     */
    minimumCacheTTL: 31_536_000,

    /*
     * Набор ширин сокращён до тех, что реально нужны вёрстке: карточка
     * (~256), витрина (~384), лист (~640) и полноэкранная сцена. Каждая
     * лишняя ширина — ещё один вариант, который сервер обязан пережать
     * и хранить.
     */
    deviceSizes: [640, 828, 1080, 1920],
    imageSizes: [96, 128, 256, 384],
  },
};

export default nextConfig;
