import type { CapacitorConfig } from "@capacitor/cli";

/**
 * Обёртка приложения для магазинов.
 *
 * Внутри нативной оболочки показывается тот же самый сайт, что и в
 * браузере, — поэтому код не дублируется, а данные остаются общими:
 * телефон, планшет и веб ходят к одному серверу. Обновление контента
 * не требует перевыпуска приложения в магазине.
 *
 * `server.url` направляет оболочку на живой сайт. Это самый надёжный
 * способ получить работающее приложение без раздвоения кода; минус —
 * нужен интернет и на бесплатном тарифе Render первая загрузка после
 * простоя ждёт пробуждения сервера. Когда понадобится офлайн-старт,
 * сюда встанет собранная статика вместо адреса.
 */
/**
 * Адрес сайта для проверочной сборки: CAP_SERVER_URL=http://10.0.2.2:3007
 * открывает локальную сборку из эмулятора (10.0.2.2 — это компьютер).
 * Без переменной — боевой сайт; открытый http разрешаем только для этой
 * проверки.
 */
const АДРЕС = process.env.CAP_SERVER_URL ?? "https://uzbekistan-travel.onrender.com";

const config: CapacitorConfig = {
  appId: "uz.uzup.app",
  appName: "HelloUZ",
  // Обязателен, даже при server.url: сюда кладётся запасная оболочка.
  // Своя крошечная папка, а не public сайта: там 250 МБ видео, и APK
  // весил бы под 300 МБ, хотя телефону эти файлы не нужны — он открывает
  // живой сайт. В оболочке только страница «Нет связи».
  webDir: "native-shell",
  server: {
    url: АДРЕС,
    // Только https. Открытый http запрещаем — это и требование магазинов,
    // и защита от подмены содержимого в пути.
    cleartext: АДРЕС.startsWith("http://"),
    // Сайт не открылся (нет сети, сервер просыпается) — своя страница
    // «Нет связи» с кнопкой «Повторить» вместо системной ошибки.
    errorPath: "offline.html",
  },
  android: {
    // Чёрный, как первый кадр заставки: пока грузится страница, не
    // мелькает белый лист, и заставка начинается без шва.
    backgroundColor: "#000000",
  },
  ios: {
    backgroundColor: "#000000",
    // Жёсткий контент-инсет: карта и колода карточек сами управляют
    // прокруткой, автоматический сдвиг webview им мешает.
    contentInset: "never",
  },
};

export default config;
