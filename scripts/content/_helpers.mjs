/** Часы работы на все дни недели. `closed` — номера выходных дней (0 = воскресенье). */
export function H(open, close, closed = []) {
  const h = {};
  for (let d = 0; d < 7; d++) {
    h[String(d)] = closed.includes(d) ? null : { open, close };
  }
  return h;
}

