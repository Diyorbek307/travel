import type { Ключ } from "@/lib/i18n";

/**
 * Страницы лендинга.
 *
 * Раньше всё было одной лентой из восемнадцати блоков — прокрутка без
 * конца, и нужное было не найти. Теперь блоки разложены по страницам:
 * на главной — коротко о главном и вход в разделы, остальное — по темам.
 * Порядок здесь — порядок в меню и в ссылке «Дальше» внизу страницы.
 */
export interface Страница {
  путь: string;
  меню: Ключ;
  знак: string;
  заголовок?: Ключ;
  текст?: Ключ;
}

export const СТРАНИЦЫ: Страница[] = [
  { путь: "/", меню: "nav_home", знак: "🏠" },
  { путь: "/app", меню: "nav_demo", знак: "📱", заголовок: "pg_app_title", текст: "pg_app_text" },
  { путь: "/uzbekistan", меню: "nav_uz", знак: "🕌", заголовок: "pg_uz_title", текст: "pg_uz_text" },
  { путь: "/trip", меню: "nav_trip", знак: "🧭", заголовок: "pg_trip_title", текст: "pg_trip_text" },
  { путь: "/esim", меню: "nav_esim", знак: "📶", заголовок: "pg_esim_title", текст: "pg_esim_text" },
  { путь: "/faq", меню: "nav_faq", знак: "💬", заголовок: "pg_faq_title", текст: "pg_faq_text" },
];

export function страница(путь: string): Страница {
  return СТРАНИЦЫ.find((с) => с.путь === путь) ?? СТРАНИЦЫ[0];
}

/** Следующая страница по кругу — для ссылки «Дальше». */
export function следующая(путь: string): Страница {
  const i = СТРАНИЦЫ.findIndex((с) => с.путь === путь);
  return СТРАНИЦЫ[(i + 1) % СТРАНИЦЫ.length] ?? СТРАНИЦЫ[0];
}
