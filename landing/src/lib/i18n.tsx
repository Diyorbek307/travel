function языкУстройства(): Язык {
  const коды = ЯЗЫКИ.map((я) => я.код);
  for (const l of navigator.languages ?? [navigator.language]) {
    const к = l.slice(0, 2).toLowerCase() as Язык;
    if (коды.includes(к)) return к;
  }
  return "en";
}

