export type Ключ = keyof typeof T;

/** Данные с подписями на части языков: нет своего — английский. */
export type Многоязычно = Partial<Record<Язык, string>> & { en: string };
export const тр = (з: Многоязычно, язык: Язык) => з[язык] ?? з.en;

function языкУстройства(): Язык {
  const коды = ЯЗЫКИ.map((я) => я.код);
  for (const l of navigator.languages ?? [navigator.language]) {
    const к = l.slice(0, 2).toLowerCase() as Язык;
    if (коды.includes(к)) return к;
  }
  return "en";
}

const Контекст = createContext<{ язык: Язык; setЯзык: (я: Язык) => void; t: (к: Ключ) => string }>({
  язык: "en",
  setЯзык: () => undefined,
  t: (к) => T[к].en,
});

export function ЯзыкProvider({ children }: { children: React.ReactNode }) {
  const [язык, setЯзыкState] = useState<Язык>("en");
  useEffect(() => {
    let сохранён: string | null = null;
    try {
      сохранён = localStorage.getItem("hz.landing.lang");
    } catch {
      // приватный режим
    }
    const коды = ЯЗЫКИ.map((я) => я.код) as string[];
    setЯзыкState(сохранён && коды.includes(сохранён) ? (сохранён as Язык) : языкУстройства());
  }, []);
  useEffect(() => {
    document.documentElement.lang = язык;
    document.documentElement.dir = язык === "ar" ? "rtl" : "ltr";
  }, [язык]);
  const setЯзык = (я: Язык) => {
    setЯзыкState(я);
    try {
      localStorage.setItem("hz.landing.lang", я);
    } catch {
      // не страшно
    }
  };
  return <Контекст.Provider value={{ язык, setЯзык, t: (к) => T[к][язык] }}>{children}</Контекст.Provider>;
}

