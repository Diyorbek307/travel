export function ЯзыкProvider({ children }: { children: React.ReactNode }) {
  const [язык, setЯзыкState] = useState<Язык>("en");
  useEffect(() => {
    let сохранён: string | null = null;
    try {
      сохранён = localStorage.getItem("hz.landing.lang");
    } catch {
      // приватный режим
    }
    const коды = ЯЗЫКИ.map((я) => я.код) as string[];
    setЯзыкState(сохранён && коды.includes(сохранён) ? (сохранён as Язык) : языкУстройства());
  }, []);
  useEffect(() => {
    document.documentElement.lang = язык;
    document.documentElement.dir = язык === "ar" ? "rtl" : "ltr";
  }, [язык]);
  const setЯзык = (я: Язык) => {
    setЯзыкState(я);
    try {
      localStorage.setItem("hz.landing.lang", я);
    } catch {
      // не страшно
    }
  };
  return <Контекст.Provider value={{ язык, setЯзык, t: (к) => T[к][язык] }}>{children}</Контекст.Provider>;
}

