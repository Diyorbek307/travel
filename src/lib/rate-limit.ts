/**
 * Ограничитель частоты запросов — защита от перебора.
 *
 * Считает в памяти процесса, сколько раз с одного ключа (обычно IP)
 * обращались за окно времени. Перебор пароля или шеститизначного кода
 * без такого тормоза — вопрос минут; с ним — практически нереален.
 *
 * Память процесса выбрана намеренно: боевой стенд работает в один
 * экземпляр, и заводить ради этого Redis рано. Если экземпляров станет
 * несколько, у каждого будет свой счётчик — тогда лимит переносят в
 * общее хранилище. Пока это честная и достаточная защита; ограничение
 * задокументировано, чтобы при масштабировании о нём вспомнили.
 */

type Корзина = { счёт: number; сбросВ: number };

const корзины = new Map<string, Корзина>();

/**
 * Уложился ли ключ в лимит.
 *
 * Возвращает `true`, если обращение разрешено, и `false`, если лимит на
 * это окно исчерпан. Само обращение засчитывается в любом случае —
 * значит перебор упрётся в стену и продлевать окно бесполезно, пока не
 * остановишься.
 *
 * @param ключ  что ограничиваем, например `login:1.2.3.4`.
 * @param лимит сколько обращений допустимо за окно.
 * @param окноМс длина окна в миллисекундах.
 */
export function подЛимитом(ключ: string, лимит: number, окноМс: number): boolean {
  const сейчас = Date.now();
  const было = корзины.get(ключ);

  if (!было || было.сбросВ < сейчас) {
    корзины.set(ключ, { счёт: 1, сбросВ: сейчас + окноМс });
    // Изредка подметаем протухшее, чтобы карта не росла без предела.
    if (корзины.size > 5000) {
      for (const [k, v] of корзины) if (v.сбросВ < сейчас) корзины.delete(k);
    }
    return true;
  }

  было.счёт += 1;
  return было.счёт <= лимит;
}

/**
 * IP клиента из заголовков.
 *
 * За Render (и любым обратным прокси) настоящий адрес приходит в
 * `x-forwarded-for` — первым в списке. Прямого соединения у приложения
 * нет, поэтому берём его; если заголовка нет, ограничиваем всех разом
 * под общим ключом, что тоже безопасно (лишь строже).
 */
export function ipЗапроса(req: Request): string {
  const forwarded = req.headers.get("x-forwarded-for");
  if (forwarded) return forwarded.split(",")[0].trim();
  return req.headers.get("x-real-ip") ?? "unknown";
}
