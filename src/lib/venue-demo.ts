export function типовыеБилеты(p: Place): Ticket[] {
  const взрослый = Number((p.entry.match(/\d+/) ?? [])[0] ?? 0);
  const id = (к: string) => `${p.id}-${к}`;
  if (!взрослый) return [{ id: id("free"), name: "Вход свободный", price: "Бесплатно" }];
  const $ = (n: number) => `$${Math.max(0.5, Math.round(n * 2) / 2)}`;
  return [
    { id: id("adult"), name: "Взрослый", price: $(взрослый) },
    { id: id("student"), name: "Студенческий (с билетом ISIC)", price: $(взрослый * 0.6) },
    { id: id("child"), name: "Детский, 7–15 лет", price: $(взрослый * 0.5) },
    { id: id("kid"), name: "Дети до 7 лет", price: "Бесплатно" },
    { id: id("local"), name: "Граждане Узбекистана", price: $(взрослый * 0.2) },
    { id: id("photo"), name: "Фотосъёмка", price: "$1" },
  ];
}

