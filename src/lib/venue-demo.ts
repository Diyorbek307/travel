function профильМеню(r: Restaurant): Record<string, Б[]> {
  const к = r.cuisine.toLowerCase();
  if (r.kind === "bar") {
    if (к.includes("вин")) return ВИНО;
    if (к.includes("клуб")) return КЛУБ;
    if (к.includes("крафт")) return КРАФТ;
    if (к.includes("лаунж")) return ЛАУНЖ;
    return БАР;
  }
  if (к.includes("fusion")) return АВТОРСКОЕ;
  if (к.includes("гриль")) return ГРИЛЬ;
  if (к.includes("рыб")) return РЫБА;
  return УЗБЕКСКОЕ;
}

/** Первые числа из «$5–15» → [5, 15]. */
function диапазон(цена: string): [number, number] {
  const ч = (цена.match(/\d+/g) ?? []).map(Number);
  const от = ч[0] ?? 5;
  return [от, ч[1] ?? от * 2];
}

/** Цена строкой: до $10 — с полудолларом, дороже — целыми. */
function $(n: number): string {
  const v = n < 10 ? Math.round(n * 2) / 2 : Math.round(n);
  return `$${v}`;
}

export function типовоеМеню(r: Restaurant): MenuItem[] {
  const профиль = профильМеню(r);
  const [от] = диапазон(r.price);
  // Цены заготовки — для типичного заведения своего профиля (чайхана
  // «от $4», авторский ресторан «от $10»). Дороже типичного — чуть
  // дороже и блюда, но не в разы: ценник «от» говорит о самом дешёвом.
  const к = Math.min(1.5, Math.max(0.8, от / (ТИПИЧНО_ОТ.get(профиль) ?? 4)));
  const h = хэш(r.id);
  const меню: MenuItem[] = [];
  Object.entries(профиль).forEach(([раздел, блюда], ри) => {
    let список = блюда;
    if (раздел === "Плов") {
      const свой = ПЛОВ_ГОРОДА[r.city] ?? ПЛОВ_ГОРОДА.Ташкент;
      список = [свой, ...блюда];
    }
    // Каждое заведение берёт из раздела своё подмножество: 3–5 блюд.
    const сколько = Math.min(список.length, 3 + ((h >> ри) % 3));
    const старт = (h + ри * 7) % список.length;
    const взято =
      раздел === "Плов"
        ? список.slice(0, сколько)
        : Array.from({ length: сколько }, (_, i) => список[(старт + i) % список.length]);
    взято.forEach(([name, desc, цена], i) =>
      меню.push({
        id: `${r.id}-m${ри}-${i}`,
        section: раздел,
        name,
        price: $(цена * к),
        ...(desc ? { desc } : {}),
      }),
    );
  });
  return меню;
}

// ── Залы, столы, средний чек ─────────────────────────────────────────

export function типовыеЗалы(r: Restaurant): Zone[] {
  const id = (к: string) => `${r.id}-z${к}`;
  if (r.kind === "bar") {
    const к = r.cuisine.toLowerCase();
    const залы: Zone[] = [
      { id: id("bar"), name: "Барная стойка", seats: 12 },
      { id: id("lounge"), name: к.includes("клуб") ? "Танцпол и VIP-ложи" : "Лаунж-зона", seats: 40 },
    ];
    if (/крыш|пляж|terrace/i.test(к + r.desc))
      залы.push({ id: id("roof"), name: "Открытая терраса", seats: 30 });
    return залы;
  }
  const традиционный = профильМеню(r) === УЗБЕКСКОЕ || профильМеню(r) === ГРИЛЬ;
  return [
    { id: id("hall"), name: "Основной зал", seats: 60 + (хэш(r.id) % 4) * 20 },
    {
      id: id("terrace"),
      name: /террас|вид|двор/i.test(r.desc) ? "Терраса с видом" : "Летняя терраса",
      seats: 40,
    },
    традиционный
      ? { id: id("topchan"), name: "Топчаны во дворе", seats: 24 }
      : { id: id("vip"), name: "Отдельный кабинет", seats: 12 },
  ];
}

export function типовыеСтолы(r: Restaurant): TableType[] {
  const h = хэш(r.id);
  const бар = r.kind === "bar";
  return [
    { id: `${r.id}-t2`, seats: 2, count: 6 + (h % 5) },
    { id: `${r.id}-t4`, seats: 4, count: 8 + (h % 6) },
    { id: `${r.id}-t6`, seats: 6, count: 3 + (h % 3) },
    ...(бар ? [] : [{ id: `${r.id}-t10`, seats: 10, count: 1 + (h % 2) }]),
  ];
}

export function типовойЧек(r: Restaurant): string {
  const [от, до] = диапазон(r.price);
  const середина = (от + до) / 2;
  return `$${Math.round(середина * 0.8)}–${Math.round(середина * 1.2)}`;
}

