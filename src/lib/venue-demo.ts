/*
 * В исходных данных обложкой многих узбекских ресторанов стояла пицца —
 * одна и та же на десяток заведений. Такую обложку меняем на снимок зала.
 */
const ПИЦЦА = "photo-1565299624946";

export function обложкаРесторана(r: Restaurant): string {
  if (!r.img.includes(ПИЦЦА)) return r.img;
  return выбрать(ФОТО.залУзбекский, r.id, 1)[0];
}

export function галереяРесторана(r: Restaurant): string[] {
  const к = r.cuisine.toLowerCase();
  const залы =
    r.kind === "bar"
      ? к.includes("клуб")
        ? ФОТО.клуб
        : к.includes("вин")
        ? ФОТО.вино
        : ФОТО.бар
      : профильМеню(r) === АВТОРСКОЕ
      ? ФОТО.залРесторана
      : ФОТО.залУзбекский;
  const обложка = обложкаРесторана(r);
  return [обложка, ...выбрать(залы, r.id, 3, обложка), ...выбрать(ФОТО.терраса, r.id, 2)];
}

export function галереяГостиницы(h: Hotel): string[] {
  const свои = h.imgs?.length ? h.imgs : [h.img];
  const номера = h.kind === "hostel" ? ФОТО.хостел : ФОТО.номер;
  return [
    ...свои,
    ...выбрать(ФОТО.лобби, h.id, 1),
    ...выбрать(номера, h.id, 2),
    ...выбрать(ФОТО.ванная, h.id, 1),
    ...(h.facilities.includes("Бассейн") ? выбрать(ФОТО.бассейн, h.id, 1) : []),
  ].filter((x, i, все) => все.indexOf(x) === i);
}

/** Места: виды города вокруг — снимков самого объекта в наборе нет. */
export function галереяМеста(p: Place): string[] {
  const город = ФОТО_ГОРОДА[p.city];
  return город ? [p.img, ...выбрать(город, p.id, 4, p.img)] : [];
}
