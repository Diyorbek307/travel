import { describe, expect, it } from "vitest";
import { подЛимитом } from "./rate-limit";

/**
 * Ограничитель — это защита от перебора пароля и кода. Проверяем, что он
 * действительно пропускает ровно N обращений, дальше запирает, и что
 * после окна снова открывает. Ключи у каждого теста разные, иначе они
 * делили бы один общий счётчик в памяти модуля.
 */
describe("подЛимитом", () => {
  it("пропускает обращения в пределах лимита", () => {
    const ключ = `t-под-${Math.random()}`;
    expect(подЛимитом(ключ, 3, 60_000)).toBe(true);
    expect(подЛимитом(ключ, 3, 60_000)).toBe(true);
    expect(подЛимитом(ключ, 3, 60_000)).toBe(true);
  });

  it("запирает на попытке сверх лимита", () => {
    const ключ = `t-сверх-${Math.random()}`;
    подЛимитом(ключ, 2, 60_000);
    подЛимитом(ключ, 2, 60_000);
    expect(подЛимитом(ключ, 2, 60_000)).toBe(false);
    expect(подЛимитом(ключ, 2, 60_000)).toBe(false);
  });

  it("разные ключи считаются независимо", () => {
    const a = `t-a-${Math.random()}`;
    const b = `t-b-${Math.random()}`;
    подЛимитом(a, 1, 60_000);
    expect(подЛимитом(a, 1, 60_000)).toBe(false); // a исчерпан
    expect(подЛимитом(b, 1, 60_000)).toBe(true); // b свободен
  });

  it("после окна счётчик сбрасывается", async () => {
    const ключ = `t-окно-${Math.random()}`;
    expect(подЛимитом(ключ, 1, 20)).toBe(true);
    expect(подЛимитом(ключ, 1, 20)).toBe(false);
    await new Promise((r) => setTimeout(r, 30));
    expect(подЛимитом(ключ, 1, 20)).toBe(true); // окно прошло — снова можно
  });
});
