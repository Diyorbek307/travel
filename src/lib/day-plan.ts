import type { Place, Restaurant } from "@/lib/types";
import { МЕСТА, расстояниеТочноКм } from "@/data/geo";
import { ТИПЫ_МЕСТ } from "@/data/content";

/**
 * Маршрут на день по городу, времени и интересам.
 *
 * Раньше на месте этого экрана показывался один и тот же маршрут по
 * Самарканду — какой бы город, время и интересы человек ни выбрал, хоть
 * Хиву. Теперь план собирается из настоящих мест выбранного города:
 * сперва подходящие по интересам, потом остальные по рейтингу; столько,
 * сколько влезает во время, с обедом в ресторане того же города.
 */

export type Интерес = "история" | "мечети" | "еда" | "природа" | "базары" | "музеи";

const ТИПЫ_ИНТЕРЕСА: Record<Exclude<Интерес, "еда">, string[]> = {
  история: ТИПЫ_МЕСТ["История"],
  мечети: ТИПЫ_МЕСТ["Мечети"],
  музеи: ТИПЫ_МЕСТ["Музеи"],
  природа: ТИПЫ_МЕСТ["Природа"],
  базары: ТИПЫ_МЕСТ["Базары"],
};

/** Сколько часов обычно проводят на месте такого типа. */
function часовНаМесте(тип: string): number {
  if (тип === "Музей") return 1.5;
  if (тип === "Природа") return 2;
  if (тип === "Мечеть" || тип === "Мавзолей" || тип === "Минарет") return 0.75;
  return 1;
}

/** Переезд между точками — с запасом на дорогу по городу. */
const ПЕРЕЕЗД_Ч = 0.25;
const НАЧАЛО_Ч = 9;

export interface Остановка {
  /** «09:00». */
  время: string;
  часов: number;
  место?: Place;
  обед?: Restaurant;
}

export interface ПланДня {
  остановки: Остановка[];
  /** Сумма прямых расстояний между точками; null — координат не хватило. */
  км: number | null;
  /** Входные билеты в долларах, сколько известно по данным. */
  вход: number;
}

function часыМинуты(ч: number): string {
  const м = Math.round(ч * 60);
  return `${String(Math.floor(м / 60)).padStart(2, "0")}:${String(м % 60).padStart(2, "0")}`;
}

/** Порядок обхода: каждый раз к ближайшей из оставшихся точек. */
function поБлизости(места: Place[]): Place[] {
  const сКоорд = места.filter((p) => МЕСТА[p.nameRu ?? p.name]);
  const безКоорд = места.filter((p) => !МЕСТА[p.nameRu ?? p.name]);
  if (сКоорд.length < 2) return места;
  const путь = [сКоорд[0]];
  const остались = сКоорд.slice(1);
  while (остались.length) {
    const здесь = МЕСТА[путь[путь.length - 1].nameRu ?? путь[путь.length - 1].name];
    let лучший = 0;
    остались.forEach((p, i) => {
      const d = расстояниеТочноКм(здесь, МЕСТА[p.nameRu ?? p.name]);
      const dЛучш = расстояниеТочноКм(здесь, МЕСТА[остались[лучший].nameRu ?? остались[лучший].name]);
      if (d < dЛучш) лучший = i;
    });
    путь.push(остались.splice(лучший, 1)[0]);
  }
  return [...путь, ...безКоорд];
}

export function планДня({
  места,
  рестораны,
  город,
  часов,
  интересы,
}: {
  места: Place[];
  рестораны: Restaurant[];
  город: string;
  часов: number;
  интересы: Интерес[];
}): ПланДня {
  const нужныеТипы = new Set(
    интересы.flatMap((и) => (и === "еда" ? [] : ТИПЫ_ИНТЕРЕСА[и])),
  );
  const подходит = (p: Place) => нужныеТипы.has(p.typeRu ?? p.type);
  const вГороде = места.filter((p) => p.city === город);
  const поПорядку = [
    ...вГороде.filter(подходит).sort((a, b) => b.rating - a.rating),
    ...вГороде.filter((p) => !подходит(p)).sort((a, b) => b.rating - a.rating),
  ];

  // Сколько мест влезает во время (обед, если будет, — отдельно).
  const сОбедом = рестораны.some((r) => r.city === город) && (интересы.includes("еда") || часов >= 6);
  const наМеста = часов - (сОбедом ? 1 : 0);
  const выбрано: Place[] = [];
  let занято = 0;
  for (const p of поПорядку) {
    const нужно = часовНаМесте(p.typeRu ?? p.type) + (выбрано.length ? ПЕРЕЕЗД_Ч : 0);
    if (занято + нужно > наМеста) continue;
    выбрано.push(p);
    занято += нужно;
  }

  // Расписание: по порядку обхода, обед — первым после полудня.
  const остановки: Остановка[] = [];
  let сейчас = НАЧАЛО_Ч;
  const лучшийРесторан = рестораны
    .filter((r) => r.city === город)
    .sort((a, b) => b.rating - a.rating)[0];
  let пообедали = !сОбедом;
  for (const p of поБлизости(выбрано)) {
    if (!пообедали && сейчас >= 12.5 && лучшийРесторан) {
      остановки.push({ время: часыМинуты(сейчас), часов: 1, обед: лучшийРесторан });
      сейчас += 1 + ПЕРЕЕЗД_Ч;
      пообедали = true;
    }
    const д = часовНаМесте(p.typeRu ?? p.type);
    остановки.push({ время: часыМинуты(сейчас), часов: д, место: p });
    сейчас += д + ПЕРЕЕЗД_Ч;
  }
  if (!пообедали && лучшийРесторан) {
    остановки.push({ время: часыМинуты(сейчас), часов: 1, обед: лучшийРесторан });
  }

  // Прямые расстояния между соседними местами, где известны координаты.
  const точки = остановки
    .map((о) => о.место && МЕСТА[о.место.nameRu ?? о.место.name])
    .filter((т): т is NonNullable<typeof т> => Boolean(т));
  const км =
    точки.length >= 2
      ? Math.round(точки.slice(1).reduce((s, т, i) => s + расстояниеТочноКм(точки[i], т), 0) * 10) / 10
      : null;

  const вход = выбрано.reduce((s, p) => s + (Number(p.entry.match(/\$(\d+)/)?.[1]) || 0), 0);

  return { остановки, км, вход };
}
