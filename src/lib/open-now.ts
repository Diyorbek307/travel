/**
 * «Открыто сейчас» по часам работы из карточки.
 *
 * Часы в данных — строкой: «09:00–18:00», «18:00–02:00» (через полночь),
 * «Всегда». Что не разобрали («Весна–осень», «по записи») — не угадываем,
 * просто ничего не показываем.
 *
 * Время берём ташкентское (UTC+5, без перехода на летнее), а не часы
 * телефона: у только что прилетевшего туриста телефон нередко ещё живёт
 * в домашнем поясе, и «открыто» соврало бы на несколько часов.
 */

export type Открытость =
  | { открыто: true; круглосуточно: true }
  | { открыто: true; круглосуточно?: false; до: string }
  | { открыто: false; откроется: string };

const ТАШКЕНТ_МИН = 5 * 60;
const СУТКИ = 24 * 60;

const ВСЕГДА = /^(всегда|круглосуточно|24\/7|24 ?ч)$/i;
const ПРОМЕЖУТОК = /(\d{1,2}):(\d{2})\s*[–—-]\s*(\d{1,2}):(\d{2})/;

const вСтроку = (мин: number) => {
  const м = ((мин % СУТКИ) + СУТКИ) % СУТКИ;
  return `${String(Math.floor(м / 60)).padStart(2, "0")}:${String(м % 60).padStart(2, "0")}`;
};

/** Минуты от полуночи по Ташкенту. */
export function минутыТашкента(сейчас: Date): number {
  return (сейчас.getUTCHours() * 60 + сейчас.getUTCMinutes() + ТАШКЕНТ_МИН) % СУТКИ;
}

export function открытоСейчас(часы: string | undefined, сейчас: Date = new Date()): Открытость | null {
  const строка = (часы ?? "").trim();
  if (!строка) return null;
  if (ВСЕГДА.test(строка)) return { открыто: true, круглосуточно: true };
  const м = ПРОМЕЖУТОК.exec(строка);
  if (!м) return null;
  const с = Number(м[1]) * 60 + Number(м[2]);
  let по = Number(м[3]) * 60 + Number(м[4]);
  if (с >= СУТКИ || по > СУТКИ) return null;
  if (с === по) return { открыто: true, круглосуточно: true };
  // «18:00–02:00» — закрываются после полуночи.
  if (по <= с) по += СУТКИ;
  let т = минутыТашкента(сейчас);
  // Ночь после полуночи относится ко вчерашней смене.
  if (т < с && т + СУТКИ < по) т += СУТКИ;
  if (т >= с && т < по) return { открыто: true, до: вСтроку(по) };
  return { открыто: false, откроется: вСтроку(с) };
}
