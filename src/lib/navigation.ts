import type { Geo } from "@/lib/types";
import type { Шаг } from "@/lib/routing";

/**
 * Ведение по маршруту: где человек на линии дороги, сколько до поворота,
 * не сбился ли он и когда пора говорить.
 *
 * Здесь только арифметика, без экрана и без GPS, — её проверяют тесты.
 * Расстояния в метрах. На расстояниях одного города Земля плоская с
 * точностью до сантиметров, поэтому считаем в местной плоской проекции.
 */

const М_НА_ГРАДУС = 111_320;

/** Расстояние между точками в метрах. */
export function метрыМежду(a: Geo, b: Geo): number {
  const кос = Math.cos((((a.lat + b.lat) / 2) * Math.PI) / 180);
  const dx = (b.lon - a.lon) * М_НА_ГРАДУС * кос;
  const dy = (b.lat - a.lat) * М_НА_ГРАДУС;
  return Math.hypot(dx, dy);
}

/** Сколько пройдено по линии до каждой её вершины. */
export function накопленные(линия: Geo[]): number[] {
  const итог = [0];
  for (let i = 1; i < линия.length; i++) итог.push(итог[i - 1] + метрыМежду(линия[i - 1], линия[i]));
  return итог;
}

export interface Привязка {
  /** Как далеко человек от линии дороги. */
  отЛинии: number;
  /** Сколько метров маршрута уже позади. */
  пройдено: number;
  /** Ближайшая точка на линии. */
  на: Geo;
}

/**
 * Ближайшая к человеку точка дороги. Ищем по всем отрезкам: дорога может
 * петлять, и «ближайший по номеру» отрезок не всегда ближайший на деле.
 * С отрезков позади (дальше 30 м от уже пройденного) не перескакиваем —
 * иначе на петле человека «отбросит» назад.
 */
export function привязать(линия: Geo[], накоп: number[], т: Geo, былоПройдено = 0): Привязка {
  const кос = Math.cos((т.lat * Math.PI) / 180);
  const x = (g: Geo) => (g.lon - т.lon) * М_НА_ГРАДУС * кос;
  const y = (g: Geo) => (g.lat - т.lat) * М_НА_ГРАДУС;

  let лучший: Привязка = { отЛинии: Infinity, пройдено: 0, на: линия[0] };
  for (let i = 0; i < линия.length - 1; i++) {
    if (накоп[i + 1] < былоПройдено - 30) continue;
    const ax = x(линия[i]);
    const ay = y(линия[i]);
    const bx = x(линия[i + 1]);
    const by = y(линия[i + 1]);
    const dx = bx - ax;
    const dy = by - ay;
    const длина2 = dx * dx + dy * dy;
    // Доля отрезка, на которую падает перпендикуляр от человека (0 в начале).
    const доля = длина2 > 0 ? Math.min(1, Math.max(0, -(ax * dx + ay * dy) / длина2)) : 0;
    const px = ax + доля * dx;
    const py = ay + доля * dy;
    const от = Math.hypot(px, py);
    if (от < лучший.отЛинии) {
      лучший = {
        отЛинии: от,
        пройдено: накоп[i] + доля * (накоп[i + 1] - накоп[i]),
        на: {
          lat: линия[i].lat + доля * (линия[i + 1].lat - линия[i].lat),
          lon: линия[i].lon + доля * (линия[i + 1].lon - линия[i].lon),
        },
      };
    }
  }
  return лучший;
}

/**
 * Где на линии стоит каждый манёвр (в метрах от начала). Ищем ближайшую
 * вершину, двигаясь только вперёд: манёвры идут по порядку, а дорога
 * может пройти мимо одного перекрёстка дважды.
 */
export function местаШагов(линия: Geo[], накоп: number[], шаги: Шаг[]): number[] {
  const итог: number[] = [];
  let с = 0;
  for (const ш of шаги) {
    let лучший = с;
    let мин = Infinity;
    for (let i = с; i < линия.length; i++) {
      const d = метрыМежду(линия[i], ш.где);
      if (d < мин) {
        мин = d;
        лучший = i;
      }
      // Ушли далеко за найденное — дальше искать нечего.
      if (мин < 5 && d > 200) break;
    }
    итог.push(накоп[лучший]);
    с = лучший;
  }
  return итог;
}

export interface Положение {
  /** Номер следующего манёвра в списке шагов. */
  следующий: number;
  /** Метров до него. */
  доМанёвра: number;
  /** Метров до цели по дороге. */
  осталось: number;
}

/** Следующий манёвр — первый, который ещё впереди. Старт не считается. */
export function положение(места: number[], всего: number, пройдено: number): Положение {
  let следующий = места.length - 1;
  for (let i = 1; i < места.length; i++) {
    // Пять метров запаса: стоя на самом перекрёстке, человек его ещё не прошёл.
    if (места[i] > пройдено - 5) {
      следующий = i;
      break;
    }
  }
  return {
    следующий: Math.max(0, следующий),
    доМанёвра: Math.max(0, (места[следующий] ?? всего) - пройдено),
    осталось: Math.max(0, всего - пройдено),
  };
}

export type Способ = "пешком" | "авто";

/**
 * Когда говорить о повороте: заранее и в самый момент.
 * Пешком хватает 60 м и 15 м; на машине нужно раньше — 500, 200 и 40 м.
 */
export const ПОРОГИ: Record<Способ, { заранее: number[]; сейчас: number }> = {
  пешком: { заранее: [60], сейчас: 15 },
  авто: { заранее: [500, 200], сейчас: 40 },
};

/**
 * Какой порог пора объявить, или null. Порог объявляется один раз:
 * сказанные помним снаружи в наборе «шаг|порог».
 * Заранее — только если до манёвра действительно далеко: сообщать «через
 * 500 м» на улице длиной 120 м было бы неправдой.
 */
export function пораСказать(
  способ: Способ,
  шаг: number,
  доМанёвра: number,
  длинаШага: number,
  сказано: Set<string>,
): { порог: number; сейчас: boolean } | null {
  const п = ПОРОГИ[способ];
  if (доМанёвра <= п.сейчас) {
    const к = `${шаг}|0`;
    return сказано.has(к) ? null : { порог: 0, сейчас: true };
  }
  // Берём самый близкий из порогов, который уже наступил: GPS обновляется
  // раз в секунду, и на машине точное число метров легко проскочить —
  // тогда фраза всё равно прозвучит, просто с настоящим расстоянием.
  const порог = [...п.заранее].sort((x, y) => x - y).find((x) => доМанёвра <= x);
  if (порог === undefined || длинаШага <= порог * 0.8) return null;
  const к = `${шаг}|${порог}`;
  return сказано.has(к) ? null : { порог, сейчас: false };
}

/** Сбился ли человек: дальше этого от линии — пересчитываем путь. */
export function сбился(отЛинии: number, точность: number, способ: Способ): boolean {
  const допуск = способ === "пешком" ? 35 : 50;
  // Когда GPS сам ошибается на 60 м, «ушёл на 40 м» ничего не значит.
  return отЛинии > Math.max(допуск, Math.min(точность, 100) * 1.2);
}

/** Круглое число метров для фразы: «через 150 м», а не «через 147 м». */
export function круглыеМетры(м: number): number {
  if (м < 100) return Math.max(10, Math.round(м / 10) * 10);
  if (м < 500) return Math.round(м / 50) * 50;
  return Math.round(м / 100) * 100;
}
