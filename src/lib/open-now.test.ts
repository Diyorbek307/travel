import { describe, expect, it } from "vitest";
import { открытоСейчас } from "./open-now";

/** Момент по Ташкенту (UTC+5). */
const вТашкенте = (ч: number, м = 0) => new Date(Date.UTC(2026, 8, 30, ч - 5, м));

describe("открытоСейчас", () => {
  it("днём в рабочие часы — открыто до конца смены", () => {
    expect(открытоСейчас("09:00–18:00", вТашкенте(12))).toEqual({ открыто: true, до: "18:00" });
  });
  it("до открытия и после закрытия — закрыто, с временем открытия", () => {
    expect(открытоСейчас("09:00–18:00", вТашкенте(7))).toEqual({ открыто: false, откроется: "09:00" });
    expect(открытоСейчас("09:00–18:00", вТашкенте(18))).toEqual({ открыто: false, откроется: "09:00" });
  });
  it("через полночь: бар 18:00–02:00 открыт в час ночи и закрыт днём", () => {
    expect(открытоСейчас("18:00–02:00", вТашкенте(1))).toEqual({ открыто: true, до: "02:00" });
    expect(открытоСейчас("18:00–02:00", вТашкенте(23))).toEqual({ открыто: true, до: "02:00" });
    expect(открытоСейчас("18:00–02:00", вТашкенте(14))).toEqual({ открыто: false, откроется: "18:00" });
    expect(открытоСейчас("18:00–00:00", вТашкенте(21))).toEqual({ открыто: true, до: "00:00" });
  });
  it("считает по Ташкенту, а не по часам телефона", () => {
    // 12:00 по Ташкенту = 07:00 UTC — в Москве 10:00, в Нью-Йорке 03:00.
    expect(открытоСейчас("10:00–17:00", new Date(Date.UTC(2026, 8, 30, 7)))?.открыто).toBe(true);
  });
  it("«Всегда» — круглосуточно, непонятное — null", () => {
    expect(открытоСейчас("Всегда")).toEqual({ открыто: true, круглосуточно: true });
    expect(открытоСейчас("Весна–осень")).toBeNull();
    expect(открытоСейчас("")).toBeNull();
    expect(открытоСейчас(undefined)).toBeNull();
  });
  it("дефис вместо тире и однозначные часы", () => {
    expect(открытоСейчас("9:00-18:00", вТашкенте(10))).toEqual({ открыто: true, до: "18:00" });
  });
});
