/** Устойчивое число из строки: у записи всегда один и тот же набор. */
export function хэш(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}

/** n снимков из набора, начиная с места, которое задаёт ключ. */
export function выбрать(набор: string[], ключ: string, n: number, кроме?: string): string[] {
  const старт = хэш(ключ) % набор.length;
  const итог: string[] = [];
  for (let i = 0; i < набор.length && итог.length < n; i++) {
    const x = набор[(старт + i) % набор.length];
    if (x !== кроме) итог.push(x);
  }
  return итог;
}
