/**
 * Секреты приложения — в одном месте и с одним правилом.
 *
 * Подписи cookie (сессия пользователя и вход в админку) и общий пароль
 * панели держатся на этих значениях. Раньше при отсутствии переменной
 * код молча подставлял известное значение по умолчанию — «admin» для
 * пароля, «uz-…-dev-secret» для подписи. Это самый опасный вид поломки:
 * снаружи всё работает, но кто угодно, знающий эти дефолты, подделывает
 * сессию любого пользователя или заходит в админку. Тихо и полностью
 * открыто.
 *
 * Правило простое: в продакшене секрет обязателен. Не задан — падаем с
 * понятной ошибкой на первом же обращении, а не запускаемся уязвимыми.
 * Пусть лучше раздел не откроется, чем откроется всем. На машине
 * разработчика (NODE_ENV !== "production") берётся временное значение,
 * чтобы не заводить переменные ради локального запуска.
 */

const вБою = process.env.NODE_ENV === "production";

/**
 * Вернуть секрет или упасть.
 *
 * @param имя      как переменная называется в окружении — попадёт в текст
 *                 ошибки, чтобы было ясно, что именно задать.
 * @param значение то, что пришло из `process.env` (может быть пустым).
 * @param запасной значение только для разработки; в бою игнорируется.
 */
export function требуетсяСекрет(имя: string, значение: string | undefined, запасной: string): string {
  if (значение && значение.length > 0) return значение;
  if (вБою) {
    throw new Error(
      `Переменная окружения ${имя} не задана. В продакшене это обязательный ` +
        `секрет: без него подписи cookie и вход в админку можно подделать. ` +
        `Задайте ${имя} (например, случайные 32 байта в hex: ` +
        `node -e "console.log(require('crypto').randomBytes(32).toString('hex'))").`,
    );
  }
  return запасной;
}

/** В бою секрет обязателен, значит режим по умолчанию — небезопасный. */
export function вПродакшене(): boolean {
  return вБою;
}
