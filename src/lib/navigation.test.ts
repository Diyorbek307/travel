import { describe, expect, it } from "vitest";
import {
  круглыеМетры,
  местаШагов,
  метрыМежду,
  накопленные,
  положение,
  пораСказать,
  привязать,
  сбился,
} from "./navigation";
import { манёврOsrm, шагиOsrm, склеитьПрямо, type Шаг } from "./routing";

// Г-образный путь в Ташкенте: 200 м на восток, потом 200 м на север.
const А = { lat: 41.3, lon: 69.2 };
const восток = 200 / (111_320 * Math.cos((41.3 * Math.PI) / 180));
const Б = { lat: 41.3, lon: 69.2 + восток };
const В = { lat: 41.3 + 200 / 111_320, lon: 69.2 + восток };
const линия = [А, Б, В];
const накоп = накопленные(линия);

const шаг = (манёвр: Шаг["манёвр"], где: Шаг["где"], метры = 0): Шаг => ({
  манёвр,
  улица: "",
  метры,
  секунды: 0,
  где,
});

describe("навигация", () => {
  it("расстояния по линии", () => {
    expect(метрыМежду(А, Б)).toBeCloseTo(200, 0);
    expect(накоп[2]).toBeCloseTo(400, 0);
  });

  it("привязка к дороге", () => {
    // 100 м на восток и 10 м южнее дороги.
    const т = { lat: 41.3 - 10 / 111_320, lon: 69.2 + восток / 2 };
    const п = привязать(линия, накоп, т);
    expect(п.отЛинии).toBeCloseTo(10, 0);
    expect(п.пройдено).toBeCloseTo(100, 0);
  });

  it("следующий поворот и сколько до него", () => {
    const места = местаШагов(линия, накоп, [шаг("старт", А, 200), шаг("налево", Б, 200), шаг("финиш", В)]);
    expect(места.map(Math.round)).toEqual([0, 200, 400]);
    const п = положение(места, 400, 50);
    expect(п.следующий).toBe(1);
    expect(Math.round(п.доМанёвра)).toBe(150);
    expect(Math.round(п.осталось)).toBe(350);
    // Прошли поворот — следующим становится финиш.
    expect(положение(места, 400, 260).следующий).toBe(2);
  });

  it("объявляем заранее и в момент, по разу", () => {
    const сказано = new Set<string>();
    expect(пораСказать("пешком", 1, 58, 200, сказано)).toEqual({ порог: 60, сейчас: false });
    сказано.add("1|60");
    expect(пораСказать("пешком", 1, 50, 200, сказано)).toBeNull();
    expect(пораСказать("пешком", 1, 12, 200, сказано)).toEqual({ порог: 0, сейчас: true });
    // Короткая улица — «через 500 м» не говорим.
    expect(пораСказать("авто", 2, 480, 150, new Set())).toBeNull();
    // Проскочили окно 200 м между сигналами GPS — всё равно объявляем.
    expect(пораСказать("авто", 3, 140, 900, new Set(["3|500"]))).toEqual({ порог: 200, сейчас: false });
    // После «через 200 м» «через 500 м» уже не звучит.
    expect(пораСказать("авто", 3, 120, 900, new Set(["3|500", "3|200"]))).toBeNull();
  });

  it("сбился с пути — с поправкой на точность GPS", () => {
    expect(сбился(40, 10, "пешком")).toBe(true);
    expect(сбился(40, 60, "пешком")).toBe(false);
    expect(сбился(40, 10, "авто")).toBe(false);
  });

  it("круглые метры", () => {
    expect(круглыеМетры(147)).toBe(150);
    expect(круглыеМетры(42)).toBe(40);
    expect(круглыеМетры(730)).toBe(700);
  });
});

describe("шаги маршрута", () => {
  it("манёвры OSRM", () => {
    expect(манёврOsrm("turn", "left")).toBe("налево");
    expect(манёврOsrm("end of road", "right")).toBe("направо");
    expect(манёврOsrm("fork", "slight left")).toBe("левее");
    expect(манёврOsrm("new name", "straight")).toBe("прямо");
    expect(манёврOsrm("roundabout", "right")).toBe("кольцо");
    expect(манёврOsrm("continue", "uturn")).toBe("разворот");
  });

  it("«прямо» склеивается с предыдущим шагом", () => {
    const итог = склеитьПрямо([шаг("старт", А, 100), шаг("прямо", Б, 50), шаг("налево", В, 30)]);
    expect(итог.map((ш) => ш.манёвр)).toEqual(["старт", "налево"]);
    expect(итог[0].метры).toBe(150);
  });

  it("разбор ответа OSRM", () => {
    const шаги = шагиOsrm([
      { distance: 27, name: "", maneuver: { type: "depart", modifier: "right", location: [69.27, 41.31] } },
      { distance: 133, name: "Brodvey", maneuver: { type: "turn", modifier: "left", location: [69.28, 41.32] } },
      { distance: 50, name: "", maneuver: { type: "roundabout", modifier: "right", exit: 2, location: [69.29, 41.33] } },
      { distance: 0, name: "", maneuver: { type: "arrive", location: [69.3, 41.34] } },
    ]);
    expect(шаги.map((ш) => ш.манёвр)).toEqual(["старт", "налево", "кольцо", "финиш"]);
    expect(шаги[1]).toMatchObject({ улица: "Brodvey", где: { lat: 41.32, lon: 69.28 } });
    expect(шаги[2].съезд).toBe(2);
  });
});
