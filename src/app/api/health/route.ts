import { NextResponse } from "next/server";
import { базаНастроена } from "@/lib/storage";
import { readContent } from "@/lib/store";

export const dynamic = "force-dynamic";

/**
 * Живая проверка хранилища — без единого секрета наружу.
 *
 * Отвечает на один вопрос, который иначе никак не задать снаружи:
 * подхватилась ли внешняя база. Мало знать, что DATABASE_URL вписан —
 * строка может быть с опечаткой, база недоступна или создана не в той
 * кодировке. Поэтому здесь не только смотрим переменную, но и реально
 * читаем из хранилища: если это Postgres и он отвечает — значит данные
 * переживут перезапуск. Если чтение падает — честно говорим, что база
 * задана, но недоступна.
 *
 * Наружу отдаём только: какой бэкенд, достучались ли, и текст ошибки
 * (без строки подключения — её тут негде взять). Никаких учётных
 * записей, содержимого и ключей.
 */
export async function GET() {
  const задана = базаНастроена();
  const бэкенд = задана ? "postgres" : "file";

  let достучались = false;
  let ошибка: string | null = null;
  try {
    await readContent();
    достучались = true;
  } catch (e) {
    ошибка = e instanceof Error ? e.message : String(e);
  }

  // Персистентность гарантирована только когда бэкенд — внешняя база и
  // она отвечает. Файловое хранилище на бесплатном хостинге обнуляется
  // при каждом деплое, поэтому для него честный ответ — «нет».
  const переживётПерезапуск = задана && достучались;

  return NextResponse.json(
    {
      ok: достучались,
      storage: бэкенд,
      reachable: достучались,
      persists: переживётПерезапуск,
      error: ошибка,
    },
    { headers: { "Cache-Control": "no-store" } },
  );
}
