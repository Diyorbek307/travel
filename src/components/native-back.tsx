"use client";

import { useEffect, useRef } from "react";

/**
 * Мост для аппаратной кнопки «Назад» в нативной оболочке (Android).
 *
 * Навигация приложения держится на состоянии, а не на адресах, поэтому у
 * webview нет истории, которую могла бы отмотать системная кнопка. Без
 * этого «Назад» с любого экрана сразу закрывала бы приложение — на
 * карточке места человек ждёт возврата к списку, а не выхода.
 *
 * Здесь мы выставляем в окно функцию window.__uzupBack(): нативная
 * активность зовёт её при нажатии кнопки. Она делает тот же «шаг назад»,
 * что и стрелки на экранах, и возвращает true, если что-то закрыла, либо
 * false, если мы на самом верху (тогда нативная часть свернёт
 * приложение). В обычном браузере функция просто никем не вызывается и
 * ни на что не влияет.
 *
 * Через глобальную функцию, а не через плагин, — намеренно: одна короткая
 * нативная вставка в MainActivity надёжнее, чем привязка к версии
 * стороннего плагина, которая может разойтись с версией ядра.
 */
declare global {
  interface Window {
    __uzupBack?: () => boolean;
  }
}

export default function NativeBack({ onBack }: { onBack: () => boolean }) {
  // Ставим ссылку один раз, а зовём всегда свежий onBack: иначе при
  // каждой смене состояния пришлось бы переустанавливать функцию.
  const свежий = useRef(onBack);
  свежий.current = onBack;

  useEffect(() => {
    window.__uzupBack = () => свежий.current();
    return () => {
      delete window.__uzupBack;
    };
  }, []);

  return null;
}
