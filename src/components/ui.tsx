/** Золото на кончике крыла. */
export const LOGO_GOLD = "#E9C46A";

export function LogoMark({
  size = 30,
  tone,
  intro = false,
}: {
  size?: number;
  /** Однотонный знак (белый — на тёмных шапках и фото). Без него — фирменный градиент. */
  tone?: string;
  /** На заставке: знак плавно проявляется. */
  intro?: boolean;
}) {
  // id градиентов уникален на каждый экземпляр: знаков на странице бывает
  // несколько, а одинаковые id в SVG перебивают друг друга.
  const id = useId().replace(/:/g, "");
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 100 100"
      fill="none"
      aria-hidden
      className={intro ? "logo-rise" : undefined}
      style={{ filter: "drop-shadow(0 1px 2px rgba(0,0,0,0.3))" }}
    >
      {!tone && (
        <defs>
          <linearGradient id={`${id}h`} x1="0.1" y1="0.95" x2="0.9" y2="0.05">
            <stop offset="0" stopColor="#07685F" />
            <stop offset="0.55" stopColor="#0FB3AC" />
            <stop offset="1" stopColor="#2FD0C6" />
          </linearGradient>
          <linearGradient id={`${id}s`} x1="0" y1="1" x2="1" y2="0">
            <stop offset="0" stopColor="#0FB3AC" />
            <stop offset="0.5" stopColor="#2FD0C6" />
            <stop offset="1" stopColor={LOGO_GOLD} />
          </linearGradient>
        </defs>
      )}
      <path d={LOGO_H} fill={tone ?? `url(#${id}h)`} />
      <path d={LOGO_SWOOSH} fill={tone ?? `url(#${id}s)`} />
    </svg>
  );
}

