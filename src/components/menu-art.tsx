/**
 * Линейные рисунки для меню: посуда и цветы, а не еда. Меню одно на
 * множество ресторанов, и фото «плова вообще» соврало бы про чужой плов;
 * рисунок чайника или пиалы украшает, ничего не обещая.
 *
 * Рисуем тонкой линией в цвет золота меню (currentColor), как на
 * печатных меню: узбекский чайник, пиала, ляган, ваза с хлопком, чашка.
 */

type Рисунок = "чайник" | "пиала" | "ляган" | "ваза" | "чашка" | "веточка";

const ЛИНИЯ = {
  fill: "none",
  stroke: "currentColor",
  strokeWidth: 1.4,
  strokeLinecap: "round" as const,
  strokeLinejoin: "round" as const,
};

/** Рисунок раздела по его названию: суп — пиала, чай — чайник… */
export function рисунокРаздела(раздел: string, номер: number): Рисунок {
  const р = раздел.toLowerCase();
  if (/чай|напит|кофе|сок|коктейл|вин|пив|drink|tea|coffee/.test(р)) return "чайник";
  if (/суп|шурп|мастав|soup/.test(р)) return "пиала";
  if (/плов|горяч|основ|шашлык|гриль|mains|main/.test(р)) return "ляган";
  if (/десерт|сладк|выпеч|dessert/.test(р)) return "ваза";
  if (/салат|закуск|starter|salad/.test(р)) return "веточка";
  return (["ляган", "пиала", "ваза", "чашка", "веточка", "чайник"] as Рисунок[])[номер % 6];
}

export function РисунокМеню({ вид, size = 40 }: { вид: Рисунок; size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 48 48" aria-hidden {...ЛИНИЯ}>
      {вид === "чайник" && (
        <>
          {/* Узбекский чайник: круглый корпус, крышка с шишечкой, носик. */}
          <path d="M14 24c0-7 4.5-11 10-11s10 4 10 11-4.5 11-10 11-10-4-10-11Z" />
          <path d="M19 13.5c0-2 2.2-3.5 5-3.5s5 1.5 5 3.5" />
          <circle cx="24" cy="8.5" r="1.4" />
          <path d="M14.5 22c-3-1-5.5 0-6.5 3l-2 5" />
          <path d="M33.5 19c4 0 6 2.5 6 5.5s-2 5-5 5.5" />
          <path d="M17 24c2 1.5 4.5 2 7 2s5-.5 7-2" />
          <path d="M18 37h12" />
        </>
      )}
      {вид === "пиала" && (
        <>
          {/* Пиала с узором и парком. */}
          <path d="M9 22h30c0 8-6.5 13-15 13S9 30 9 22Z" />
          <path d="M18 35.5h12" />
          <path d="M14 26.5c3 1.5 6.5 2 10 2s7-.5 10-2" />
          <path d="M19 17c-1.5-2 1.5-3.5 0-5.5M24 17c-1.5-2 1.5-3.5 0-5.5M29 17c-1.5-2 1.5-3.5 0-5.5" />
        </>
      )}
      {вид === "ляган" && (
        <>
          {/* Ляган — большое блюдо с орнаментом, вид сверху наискосок. */}
          <ellipse cx="24" cy="27" rx="18" ry="9" />
          <ellipse cx="24" cy="26" rx="11" ry="5" />
          <path d="M24 21v-2M13 24.5l-1.5-1M35 24.5l1.5-1M17 30.5l-1 1.3M31 30.5l1 1.3" />
          <path d="M20.5 26c1-1.2 2.2-1.8 3.5-1.8s2.5.6 3.5 1.8" />
        </>
      )}
      {вид === "ваза" && (
        <>
          {/* Ваза с веткой хлопка — символом Узбекистана. */}
          <path d="M18 40h12M19.5 40c-3-3-4-7-2.5-11h14c1.5 4 .5 8-2.5 11" />
          <path d="M17 29h14" />
          <path d="M24 29V14M24 22l-6-5M24 19l6-6" />
          <circle cx="24" cy="11" r="3" />
          <circle cx="16.5" cy="15" r="2.5" />
          <circle cx="31.5" cy="11" r="2.5" />
        </>
      )}
      {вид === "чашка" && (
        <>
          <path d="M12 20h20v5c0 5.5-4.5 9-10 9s-10-3.5-10-9v-5Z" />
          <path d="M32 22.5h2.5a3.5 3.5 0 0 1 0 7H31" />
          <path d="M8 37h32" />
          <path d="M18 15c-1-1.5 1-2.5 0-4M24 15c-1-1.5 1-2.5 0-4" />
        </>
      )}
      {вид === "веточка" && (
        <>
          {/* Веточка с листьями — для салатов и закусок. */}
          <path d="M10 38C18 30 26 20 38 10" />
          <path d="M16 31c-4 0-6-3-6-6 3.5 0 6 2.5 6 6ZM22 25c-4 0-6-3-6-6 3.5 0 6 2.5 6 6ZM28 18c-4 0-6-3-6-6 3.5 0 6 2.5 6 6Z" />
          <path d="M19 30c0 4 3 6 6 6 0-3.5-2.5-6-6-6ZM25 23.5c0 4 3 6 6 6 0-3.5-2.5-6-6-6ZM31 16.5c0 4 3 6 6 6 0-3.5-2.5-6-6-6Z" />
        </>
      )}
    </svg>
  );
}

