/** Окно вида в градусах — по нему считается положение любой точки. */
export const ОКНО = {"запад":52,"восток":76,"юг":35.5,"север":47} as const;

export const ХОЛСТ = { ширина: 1000, высота: 637 } as const;

/** Переводит долготу и широту в точку на холсте. */
export function вХолст(lon: number, lat: number): { x: number; y: number } {
  const сжатие = Math.cos(((ОКНО.юг + ОКНО.север) / 2) * (Math.PI / 180));
  const шД = (ОКНО.восток - ОКНО.запад) * сжатие;
  const шШ = ОКНО.север - ОКНО.юг;
  return {
    x: ((lon - ОКНО.запад) * сжатие * ХОЛСТ.ширина) / шД,
    y: ((ОКНО.север - lat) * ХОЛСТ.высота) / шШ,
  };
}

/** Обратный перевод: точка на холсте в долготу и широту. */
export function изХолста(x: number, y: number): { lon: number; lat: number } {
  const сжатие = Math.cos(((ОКНО.юг + ОКНО.север) / 2) * (Math.PI / 180));
  const шД = (ОКНО.восток - ОКНО.запад) * сжатие;
  const шШ = ОКНО.север - ОКНО.юг;
  return {
    lon: ОКНО.запад + (x * шД) / (сжатие * ХОЛСТ.ширина),
    lat: ОКНО.север - (y * шШ) / ХОЛСТ.высота,
  };
}

/** Попадает ли точка в окно карты. */
export function вОкне(lon: number, lat: number): boolean {
  return lon >= ОКНО.запад && lon <= ОКНО.восток && lat >= ОКНО.юг && lat <= ОКНО.север;
}

