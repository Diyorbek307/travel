/** Обновить сохранённые на сайте карточки Самарканда, если их не правили в панели. */
export function обновитьМестаСамарканда<T extends { id: string; desc?: string }>(список: T[]): T[] {
  return список.map((p) => {
    const исходный = p.id.replace(/^\d+-/, "");
    const правка = САМАРКАНД_ОБНОВЛЕНИЯ[исходный];
    if (!правка || p.desc !== ПРЕЖНИЕ_ОПИСАНИЯ[исходный]) return p;
    return { ...p, ...правка };
  });
}

