/** Километры от центра города — для подписи «2.4 км» в списках. */
function отЦентра(geo: Geo): string {
  const центр = { lat: 39.654722, lon: 66.975556 }; // Регистан
  const r = 6371;
  const dLat = ((geo.lat - центр.lat) * Math.PI) / 180;
  const dLon = ((geo.lon - центр.lon) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((центр.lat * Math.PI) / 180) * Math.cos((geo.lat * Math.PI) / 180) * Math.sin(dLon / 2) ** 2;
  const км = 2 * r * Math.asin(Math.sqrt(a));
  return км < 10 ? `${км.toFixed(1)} км` : `${Math.round(км)} км`;
}

function собрать(з: Запись): Place & { geo: Geo } {
  const фото = ФОТО_САМАРКАНДА[з.id];
  const { время: _в, свято: _с, заповедник: _з, ...поля } = з;
  return {
    ...поля,
    distance: поля.distance || отЦентра(з.geo),
    // Чего не знаем — так и пишем, а не оставляем пустую клетку.
    entry: поля.entry || (з.заповедник ? "Платно" : "Уточняйте"),
    hours: поля.hours || "Уточняйте",
    rating: 0,
    reviews: 0,
    audio: false,
    qr: false,
    // Свободного фото нет — своя обложка с орнаментом, а не чужой снимок.
    img: фото?.img ?? "/places/samarkand/no-photo.svg",
    imgs: фото?.imgs ?? [],
    credits: фото?.credits,
    facts: факты(з.id, з),
    // Цен по категориям в открытых источниках нет — билеты не выдумываем.
    tickets: [],
  };
}

