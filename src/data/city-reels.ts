import type { Hotel, Place, Restaurant } from "@/lib/types";

/**
 * Кадры для короткого ролика о городе.
 *
 * Собираем из фотографий, которые уже есть в содержимом этого города:
 * достопримечательности, отели, рестораны. Так ролик всегда показывает
 * именно этот город и не зависит от внешних ссылок, которых у проекта
 * нет прав снимать.
 *
 * Если для города появится настоящий ролик, он кладётся в
 * public/videos/<латиницей>.mp4 — см. ВИДЕО ниже.
 */

/** Настоящие ролики, если они есть. Ключ — русское название города. */
export const ВИДЕО: Record<string, string> = {};

/** Сколько кадров берём: больше четырёх никто не досматривает. */
const МАКС = 4;

export function кадрыГорода(
  город: string,
  обложка: string,
  источники: { PLACES: Place[]; HOTELS: Hotel[]; RESTAURANTS: Restaurant[] },
): string[] {
  const кадры: string[] = [обложка];
  const добавить = (src?: string) => {
    if (!src || кадры.includes(src) || кадры.length >= МАКС) return;
    кадры.push(src);
  };
  // Сначала достопримечательности — они и есть лицо города,
  // потом интерьеры отелей и еда: получается смена планов, как в ролике.
  источники.PLACES.filter((p) => p.city === город).forEach((p) => добавить(p.img));
  источники.RESTAURANTS.filter((r) => r.city === город).forEach((r) => добавить(r.img));
  источники.HOTELS.filter((h) => h.city === город).forEach((h) => добавить(h.img));
  return кадры;
}
