import type { Place } from "@/lib/types";

/**
 * Кадры для короткого ролика о городе.
 *
 * Берём только достопримечательности этого города: они и есть его лицо.
 * Интерьеры отелей и тарелки из ресторанов сюда не идут — в шапке
 * «Самарканд · сердце Шёлкового пути» крупным планом оказывался салат.
 *
 * Если для города появится настоящий ролик, он кладётся в
 * public/videos/ и вписывается в ВИДЕО ниже.
 */

/** Настоящие ролики, если они есть. Ключ — русское название города. */
export const ВИДЕО: Record<string, string> = {};

/** Сколько кадров берём: больше четырёх никто не досматривает. */
const МАКС = 4;

/**
 * Один и тот же снимок приходит с разными размерами в запросе, поэтому
 * сравниваем по идентификатору фотографии, а не по всей ссылке — иначе
 * ролик «переключался» с кадра на него же.
 */
function ключКадра(src: string): string {
  return src.split("?")[0];
}

export function кадрыГорода(
  город: string,
  обложка: string,
  источники: { PLACES: Place[] },
): string[] {
  const кадры: string[] = [обложка];
  const ключи = new Set([ключКадра(обложка)]);
  for (const p of источники.PLACES) {
    if (кадры.length >= МАКС) break;
    if (p.city !== город) continue;
    const k = ключКадра(p.img);
    if (ключи.has(k)) continue;
    ключи.add(k);
    кадры.push(p.img);
  }
  return кадры;
}
