import type { Geo, Place } from "@/lib/types";
import { собрать, type ЗаписьРегиона, type ФотоМеста } from "./core";
import { МЕСТА_ТАШКЕНТА } from "./tashkent";
import { ФОТО_ТАШКЕНТА } from "./tashkent-photos";
import { МЕСТА_БУХАРЫ } from "./bukhara";
import { ФОТО_БУХАРЫ } from "./bukhara-photos";

/**
 * Все регионы, кроме Самарканда: места, их фото и переводы.
 * Новый регион — файл с местами, файл с фото и строка в списке ниже.
 */
const РЕГИОНЫ: [ЗаписьРегиона[], Record<string, ФотоМеста>][] = [
  [МЕСТА_ТАШКЕНТА, ФОТО_ТАШКЕНТА],
  [МЕСТА_БУХАРЫ, ФОТО_БУХАРЫ],
];

/**
 * Точка отсчёта «км от центра» для каждого города — главная площадь или
 * памятник, как Регистан у Самарканда. Свои копии, а не data/geo.ts:
 * geo.ts сам берёт отсюда координаты мест, и импорт шёл бы по кругу.
 */
const ЦЕНТРЫ: Record<string, Geo> = {
  Ташкент: { lat: 41.31139, lon: 69.27972 },
  Чарвак: { lat: 41.62, lon: 70.09 },
  Бухара: { lat: 39.7747, lon: 64.4286 },
  Хива: { lat: 41.3775, lon: 60.3619 },
  Нукус: { lat: 42.46, lon: 59.61 },
  Фергана: { lat: 40.3842, lon: 71.7843 },
  Коканд: { lat: 40.5286, lon: 70.9425 },
  Наманган: { lat: 40.9983, lon: 71.6726 },
  Андижан: { lat: 40.7821, lon: 72.3442 },
  Термез: { lat: 37.2242, lon: 67.2783 },
  Карши: { lat: 38.86, lon: 65.79 },
  Шахрисабз: { lat: 39.0578, lon: 66.8342 },
  Гулистан: { lat: 40.4897, lon: 68.7842 },
  Джизак: { lat: 40.1158, lon: 67.8422 },
  Навои: { lat: 40.0844, lon: 65.3792 },
};

const ВСЕ = РЕГИОНЫ.flatMap(([места, фото]) => места.map((з) => ({ з, фото: фото[з.id] })));

/** Места регионов в формате семян. */
export const РЕГИОНЫ_МЕСТА: (Place & { geo: Geo })[] = ВСЕ.map(({ з, фото }) => собрать(з, ЦЕНТРЫ[з.city], фото));

/** id мест — для поздних семян: на сайт они досыпаются один раз. */
export const РЕГИОНЫ_ID = ВСЕ.map(({ з }) => з.id);

/** Координаты по названию — для карты, такси и плана дня (data/geo.ts). */
export const РЕГИОНЫ_КООРДИНАТЫ: Record<string, Geo> = Object.fromEntries(ВСЕ.map(({ з }) => [з.name, з.geo]));

/** Переводы названий и описаний: ключ — русская строка, как во всём словаре. */
export const РЕГИОНЫ_ПЕРЕВОДЫ: [string, Partial<Record<"en" | "uz", string>>][] = ВСЕ.flatMap(({ з }) => [
  [з.name, { en: з.en.name, uz: з.uz.name }],
  [з.desc, { en: з.en.desc, uz: з.uz.desc }],
]);
